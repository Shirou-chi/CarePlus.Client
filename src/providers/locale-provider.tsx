export type Copy = {
    [K in keyof (typeof copy)["en"]]: (typeof copy)["en"][K] extends string ? string : (typeof copy)["en"][K];
};

type LocaleContextValue = {
    locale: Locale;
    setLocale: (locale: Locale) => void;
    applyLocale: (locale: Locale) => void;
    t: Copy;
};

const LocaleContext = createContext<LocaleContextValue | undefined>(undefined);

const STORAGE_KEY = "careplus-locale";

export const LocaleProvider = ({ children }: { children: ReactNode }) => {
    const [locale, setLocaleState] = useState<Locale>(() => {
        if (typeof window === "undefined") return "en";
        return window.localStorage.getItem(STORAGE_KEY) === "zh" ? "zh" : "en";
    });

    const applyLocale = useCallback((next: Locale) => {
        setLocaleState(next);
        window.localStorage.setItem(STORAGE_KEY, next);
    }, []);

    const setLocale = useCallback((next: Locale) => {
        setLocaleState(next);
        window.localStorage.setItem(STORAGE_KEY, next);
        if (getAuthToken()) {
            void profileApi.saveAppSetting({ language: next }).catch(() => undefined);
        }
    }, []);

    useEffect(() => {
        document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
    }, [locale]);

    return <LocaleContext.Provider value={{ locale, setLocale, applyLocale, t: copy[locale] }}>{children}</LocaleContext.Provider>;
};

export const useI18n = () => {
    const context = useContext(LocaleContext);
    if (!context) throw new Error("useI18n must be used within LocaleProvider");
    return context;
};
